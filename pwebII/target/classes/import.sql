
CREATE SEQUENCE revinfo_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE perfil
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    nome VARCHAR(30)                             NOT NULL,
    CONSTRAINT pk_perfil PRIMARY KEY (id)
);

CREATE TABLE pessoa
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    email      VARCHAR(255),
    telefone   VARCHAR(255),
    usuario_id BIGINT,
    CONSTRAINT pk_pessoa PRIMARY KEY (id)
);

CREATE TABLE pessoa_fisica
(
    id_pessoa       BIGINT NOT NULL,
    nome            VARCHAR(100),
    cpf             VARCHAR(255),
    data_nascimento date   NOT NULL,
    CONSTRAINT pk_pessoafisica PRIMARY KEY (id_pessoa)
);

CREATE TABLE pessoa_juridica
(
    id_pessoa    BIGINT NOT NULL,
    razao_social VARCHAR(255),
    cnpj         VARCHAR(255),
    CONSTRAINT pk_pessoajuridica PRIMARY KEY (id_pessoa)
);

CREATE TABLE revchanges
(
    rev        BIGINT NOT NULL,
    entityname VARCHAR(255)
);

CREATE TABLE revinfo
(
    rev      BIGINT NOT NULL,
    revtstmp BIGINT,
    CONSTRAINT pk_revinfo PRIMARY KEY (rev)
);

CREATE TABLE tb_consulta
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    data        date                                    NOT NULL,
    valor       DOUBLE PRECISION                        NOT NULL,
    observacao  VARCHAR(255),
    medico_id   BIGINT                                  NOT NULL,
    paciente_id BIGINT                                  NOT NULL,
    CONSTRAINT pk_tb_consulta PRIMARY KEY (id)
);

CREATE TABLE tb_medico
(
    id_pessoa_fisica BIGINT NOT NULL,
    crm              VARCHAR(255),
    CONSTRAINT pk_tb_medico PRIMARY KEY (id_pessoa_fisica)
);

CREATE TABLE tb_paciente
(
    id_pessoa_fisica BIGINT NOT NULL,
    CONSTRAINT pk_tb_paciente PRIMARY KEY (id_pessoa_fisica)
);

CREATE TABLE usuario
(
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    login    VARCHAR(255)                            NOT NULL,
    password VARCHAR(100)                            NOT NULL,
    ativo    BOOLEAN                                 NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id)
);

CREATE TABLE usuario_perfil
(
    perfil_id  BIGINT NOT NULL,
    usuario_id BIGINT NOT NULL
);

ALTER TABLE perfil
    ADD CONSTRAINT uc_perfil_nome UNIQUE (nome);

ALTER TABLE pessoa
    ADD CONSTRAINT uc_pessoa_usuario UNIQUE (usuario_id);

ALTER TABLE pessoa_fisica
    ADD CONSTRAINT uc_pessoafisica_cpf UNIQUE (cpf);

ALTER TABLE usuario
    ADD CONSTRAINT uc_usuario_login UNIQUE (login);

ALTER TABLE pessoa_fisica
    ADD CONSTRAINT FK_PESSOAFISICA_ON_ID_PESSOA FOREIGN KEY (id_pessoa) REFERENCES pessoa (id);

ALTER TABLE pessoa_juridica
    ADD CONSTRAINT FK_PESSOAJURIDICA_ON_ID_PESSOA FOREIGN KEY (id_pessoa) REFERENCES pessoa (id);

ALTER TABLE pessoa
    ADD CONSTRAINT FK_PESSOA_ON_USUARIO FOREIGN KEY (usuario_id) REFERENCES usuario (id);

ALTER TABLE tb_consulta
    ADD CONSTRAINT FK_TB_CONSULTA_ON_MEDICO FOREIGN KEY (medico_id) REFERENCES tb_medico (id_pessoa_fisica);

ALTER TABLE tb_consulta
    ADD CONSTRAINT FK_TB_CONSULTA_ON_PACIENTE FOREIGN KEY (paciente_id) REFERENCES tb_paciente (id_pessoa_fisica);

ALTER TABLE tb_medico
    ADD CONSTRAINT FK_TB_MEDICO_ON_ID_PESSOA_FISICA FOREIGN KEY (id_pessoa_fisica) REFERENCES pessoa_fisica (id_pessoa);

ALTER TABLE tb_paciente
    ADD CONSTRAINT FK_TB_PACIENTE_ON_ID_PESSOA_FISICA FOREIGN KEY (id_pessoa_fisica) REFERENCES pessoa_fisica (id_pessoa);

ALTER TABLE revchanges
    ADD CONSTRAINT fk_revchanges_on_default_tracking_modified_entities_changelog FOREIGN KEY (rev) REFERENCES revinfo (rev);

ALTER TABLE usuario_perfil
    ADD CONSTRAINT fk_usuper_on_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id);

ALTER TABLE usuario_perfil
    ADD CONSTRAINT fk_usuper_on_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id);

